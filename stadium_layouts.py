def calculate_polygon_area(coords):
    """Calculates the area of a lat/lon polygon in square meters by projecting locally."""
    if not coords or len(coords) < 3:
        return 0.0
    lats = [c[0] for c in coords]
    lons = [c[1] for c in coords]
    lat_c = sum(lats) / len(lats)
    lon_c = sum(lons) / len(lons)
    cos_lat = math.cos(math.radians(lat_c))
    
    # Project to meters relative to centroid
    proj_coords = []
    for lat, lon in coords:
        x = (lon - lon_c) * 111320.0 * cos_lat
        y = (lat - lat_c) * 111320.0
        proj_coords.append((x, y))
        
    poly = Polygon(proj_coords)
    return poly.area

def calculate_bearing(p1, p2):
    """Calculates the bearing from p1 (lat, lon) to p2 (lat, lon) in degrees."""
    lat1, lon1 = math.radians(p1[0]), math.radians(p1[1])
    lat2, lon2 = math.radians(p2[0]), math.radians(p2[1])
    dlon = lon2 - lon1
    y = math.sin(dlon) * math.cos(lat2)
    x = math.cos(lat1) * math.sin(lat2) - math.sin(lat1) * math.cos(lat2) * math.cos(dlon)
    bearing = math.atan2(y, x)
    return (math.degrees(bearing) + 360) % 360

def get_outfield_points(home_plate, bearing, left_m, l_center_m, center_m, r_center_m, right_m):
    """Computes the lat/lon coords for the outfield fence nodes."""
    # Left Pole: bearing - 45
    # Left-Center: bearing - 22.5
    # Center: bearing
    # Right-Center: bearing + 22.5
    # Right Pole: bearing + 45
    
    angles = [bearing - 45, bearing - 22.5, bearing, bearing + 22.5, bearing + 45]
    distances = [left_m, l_center_m, center_m, r_center_m, right_m]
    
    points = []
    for angle, dist in zip(angles, distances):
        # Calculate destination coordinate
        dest = geodesic(meters=dist).destination(point=home_plate, bearing=angle)
        points.append((dest.latitude, dest.longitude))
        
    return {
        "left": points[0],
        "l_center": points[1],
        "center": points[2],
        "r_center": points[3],
        "right": points[4]
    }

def get_playing_field_area(home_plate, outfield_pts):
    """Calculates the area of the playing field bounded by home plate and outfield fence nodes."""
    # Polygon order: home_plate -> left -> l_center -> center -> r_center -> right -> home_plate
    coords = [
        home_plate,
        outfield_pts["left"],
        outfield_pts["l_center"],
        outfield_pts["center"],
        outfield_pts["r_center"],
        outfield_pts["right"],
        home_plate
    ]
    return calculate_polygon_area(coords)
